const escapeHtml = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;'
})[character]);

function resolvePageKey() {
  const page = document.body.dataset.page;
  const params = new URLSearchParams(location.search);
  if (page === 'personal-documents') return params.get('context') === 'processing' ? null : 'resource-directory-personal';
  if (page === 'personal-file-detail') return 'resource-directory-personal-detail';
  return page;
}

function listMarkup(items) {
  return `<ul>${items.map(item => `<li>${escapeHtml(item)}</li>`).join('')}</ul>`;
}

export function injectResourcePageNotes() {
  const key = resolvePageKey();
  const note = key ? pageNotes[key] : null;
  const content = document.querySelector('[data-page-content]');
  if (!note || !content || content.querySelector('[data-product-rule-note]')) return;

  const details = document.createElement('details');
  details.className = `product-rule-note${note.status ? ' is-paused' : ''}`;
  details.dataset.productRuleNote = '';
  details.open = true;
  details.innerHTML = `
    <summary>
      <span class="product-rule-note-mark" aria-hidden="true">i</span>
      <span class="product-rule-note-summary">
        <strong class="text-normal-bold">业务规则与研发注意事项</strong>
        <span class="text-small">${escapeHtml(note.reference)}</span>
      </span>
      ${note.status ? `<span class="tag tag-status tag-status-secondary">${escapeHtml(note.status)}</span>` : '<span class="text-small product-rule-note-hint">点击收起</span>'}
    </summary>
    <div class="product-rule-note-body">
      <p class="product-rule-note-boundary"><strong class="text-small-bold">业务边界</strong><span>${escapeHtml(note.boundary)}</span></p>
      <section><h3 class="text-small-bold">核心业务逻辑</h3>${listMarkup(note.rules)}</section>
      <section><h3 class="text-small-bold">研发注意事项</h3>${listMarkup(note.attention)}</section>
    </div>`;

  const heading = content.querySelector('.page-heading');
  if (heading) heading.insertAdjacentElement('afterend', details);
  else content.prepend(details);

  details.addEventListener('toggle', () => {
    const hint = details.querySelector('.product-rule-note-hint');
    if (hint) hint.textContent = details.open ? '点击收起' : '点击展开';
  });
}
